/**
 * Game versions and their release notes, newest first. A release becomes
 * visible to players at `publishedAt` (staff see it earlier, to check it);
 * every player gets the "Какво ново" window once, at the first visit after
 * that. Text is Bulgarian, shown as is.
 */

export type ReleaseIcon = 'pumpkin' | 'ghost' | 'truck' | 'trophy' | 'paint' | 'scroll' | 'sparkles' | 'map' | 'bell' | 'shield' | 'chart' | 'news' | 'gavel';

export interface ReleaseHighlight {
  icon: ReleaseIcon;
  title: string;
  body: string;
}

export interface ReleaseSection {
  title: string;
  items: string[];
  /** 1.2.3.2: shown only to the staff (the admin panel and the team's tools). */
  staff?: boolean;
}

/** 1.2.3.2: titles of the sections about the admin panel and the team's tools — staff only, like `staff: true`. */
export const STAFF_SECTION_TITLES = ['За екипа', 'Админ панел'];

/** The sections a viewer may read: the team's sections only for the staff. */
export function sectionsFor(r: Release, staff: boolean): ReleaseSection[] {
  return staff ? r.sections : r.sections.filter((s) => !s.staff && !STAFF_SECTION_TITLES.includes(s.title));
}

export interface Release {
  version: string;
  name: string;
  /** ISO time the release goes live for players. */
  publishedAt: string;
  tagline: string;
  /** Seasonal look the release window uses. */
  theme?: 'halloween';
  highlights: ReleaseHighlight[];
  sections: ReleaseSection[];
}

